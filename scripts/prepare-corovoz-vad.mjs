import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { mkdir, copyFile, rm } from 'node:fs/promises'

// Serve every model/runtime asset from our own origin; no audio or CDN calls at runtime.
const require = createRequire(import.meta.url)
const vad = dirname(require.resolve('@ricky0123/vad-web'))
const target = new URL('../public/corovoz-vad/', import.meta.url)
await mkdir(target, { recursive: true })
for (const name of ['vad.worklet.bundle.min.js', 'silero_vad_v5.onnx']) {
  await copyFile(join(vad, name), new URL(name, target))
}
// Remove only files generated by the earlier public-runtime setup. Vite now emits them as assets.
for (const variant of ['', '.asyncify', '.jsep', '.jspi']) {
  for (const extension of ['mjs', 'wasm']) {
    await rm(new URL(`ort-wasm-simd-threaded${variant}.${extension}`, target), { force: true })
  }
}
